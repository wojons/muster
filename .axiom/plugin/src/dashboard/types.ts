// ---------------------------------------------------------------------------
// SessionRow — one row in the dashboard table
// ---------------------------------------------------------------------------

/**
 * A single session entry rendered as one row in the TUI table.
 *
 * - `title` is truncated to 14 chars with ellipsis at the renderer layer.
 * - `costUsd` is derived from microdollars via `microdollarsToUsd()`.
 * - `isTeam` rows suppress cost/token display (privacy for team members).
 */
export interface SessionRow {
  /** Unique session identifier. */
  sessionId: string
  /** Human-readable session title; truncated to 14 chars + ellipsis by renderer. */
  title?: string
  /** Work item ID (e.g., "AUTH-234") when known. */
  workItemId?: string
  /** Display name for the model (e.g., "Sonnet", "Opus 4"). */
  model: string
  /** Raw model ID used for alias lookup (e.g., "anthropic.claude-sonnet-4-6"). */
  modelRaw: string
  /** Session cost in USD, derived from microdollars. */
  costUsd: number
  /** Total tokens consumed (prompt + completion). */
  totalTokens: number
  /** Session wall-clock duration in seconds. */
  durationSeconds: number
  /** Current session lifecycle state. */
  status: import("../metrics/sink-interface").SessionState
  /** Which data source provided this row. */
  source: "in-memory" | "file" | "network" | "sqlite"
  /** Timestamp of the most recent data update for this session. */
  updatedAt: Date
  /** True when this row represents a team member session (suppresses cost/token display). */
  isTeam: boolean
  /** Team member identifier; only present when isTeam=true. */
  teamMemberId?: string
  /** Configured budget threshold in USD; used to render alert indicators. */
  budgetUsd?: number
  /** Session directory path (for worktree extraction). */
  directory?: string

  // --- Extended token breakdown (populated by SQLiteSource) ---
  /** Input tokens (prompt tokens sent to the model). */
  inputTokens?: number
  /** Output tokens (completion tokens generated by the model). */
  outputTokens?: number
  /** Cache read tokens (tokens served from cache, not billed at full rate). */
  cacheReadTokens?: number
  /** Cache write tokens (tokens written to cache). */
  cacheWriteTokens?: number
  /** Reasoning tokens (chain-of-thought tokens, e.g., o1/o3 models). */
  reasoningTokens?: number
  /** Number of tool call messages in this session. */
  toolCalls?: number
  /** Number of assistant messages in this session. */
  messageCount?: number
  /** Tokens per second (output tokens / duration). */
  tokensPerSecond?: number
  /**
   * tok/s history samples for sparkline history in watch mode (last 20 values).
   * Populated by the watch-mode render loop in cli.ts; absent in one-shot mode.
   *
   * axiom:trace work_item=tui-dashboard-01 spec=specs/89-TUI-Dashboard-Plugin.md#REQ-TUI-120 plan=phase-10/task-10.5
   */
  tpsSamples?: number[]
}

// ---------------------------------------------------------------------------
// DashboardAggregates — the stats bar
// ---------------------------------------------------------------------------

/**
 * Aggregate statistics displayed in the dashboard stats bar.
 *
 * `avgSpeedTokensPerSec` = totalTokens / totalDurationSeconds across all sessions.
 */
export interface DashboardAggregates {
  totalSessions: number
  totalCostUsd: number
  totalTokens: number
  /** Average token throughput: totalTokens / sum(durationSeconds). */
  avgSpeedTokensPerSec: number
}

/**
 * Per-model usage breakdown for the htop-style header meters.
 */
export interface ModelUsage {
  /** Display name (resolved from alias map). */
  model: string
  /** Raw model ID. */
  modelRaw: string
  /** Provider ID (e.g., "amazon-bedrock", "openai"). */
  provider: string
  /** Number of sessions using this model. */
  sessions: number
  /** Total LLM calls to this model. */
  calls: number
  /** Total cost in USD. */
  costUsd: number
  /** Total output tokens. */
  outputTokens: number
  /** Total input tokens. */
  inputTokens: number
  /** Total cache read tokens. */
  cacheReadTokens: number
  /** Total reasoning tokens (chain-of-thought, e.g., o1/o3 models). */
  reasoningTokens: number
  // axiom:trace work_item=tui-dashboard-01 spec=specs/89-TUI-Dashboard-Plugin.md#REQ-TUI-100 plan=F-003
}

/**
 * Per-provider usage breakdown for the htop-style header meters.
 * Aggregated from ModelUsage by provider field.
 *
 * axiom:trace work_item=tui-dashboard-01 spec=specs/89-TUI-Dashboard-Plugin.md#REQ-TUI-100 plan=phase-10/task-10.3
 */
export interface ProviderUsage {
  provider: string
  sessions: number
  calls: number
  costUsd: number
  outputTokens: number
  inputTokens: number
  cacheReadTokens: number
  reasoningTokens: number
}

// ---------------------------------------------------------------------------
// SourceStatus — freshness info per data source
// ---------------------------------------------------------------------------

/**
 * Availability and freshness metadata for a single data source.
 *
 * `lastUpdate` is null when the source has never successfully returned data.
 */
export interface SourceStatus {
  available: boolean
  lastUpdate: Date | null
  /** Human-readable error message when available=false. */
  error?: string
}

// ---------------------------------------------------------------------------
// DashboardData — full payload passed to the renderer
// ---------------------------------------------------------------------------

/**
 * The complete data payload consumed by the TUI renderer.
 *
 * Produced by `SessionDataCollector` and passed directly to the table renderer.
 * All sources are merged and deduplicated before this payload is assembled.
 */
export interface DashboardData {
  /** Merged, deduplicated session rows ordered by updatedAt descending. */
  sessions: SessionRow[]
  /** Aggregate stats computed across all sessions. */
  aggregates: DashboardAggregates
  /** Per-source availability and freshness metadata. */
  sources: {
    inMemory: SourceStatus
    file: SourceStatus
    network: SourceStatus
  }
  /** Timestamp when this payload was assembled. */
  generatedAt: Date
  /** Per-model usage breakdown for header meters (populated by SQLiteSource). */
  modelUsage?: ModelUsage[]
}

// ---------------------------------------------------------------------------
// SessionDataSource — interface each source must implement
// ---------------------------------------------------------------------------

/**
 * Contract for a single data source in the unified `SessionDataCollector`.
 *
 * Priority order (higher = preferred for deduplication):
 *   in-memory (3) > file (2) > network (1)
 *
 * Sources are polled once per tool invocation (one-shot execution model).
 */
export interface SessionDataSource {
  /** Stable source identifier used for deduplication and SourceStatus keying. */
  readonly id: "in-memory" | "file" | "network" | "sqlite"
  /** Deduplication priority: higher value wins when the same sessionId appears in multiple sources. */
  readonly priority: number
  /** Fetch all sessions available from this source. */
  getSessions(): Promise<SessionRow[]>
  /** Returns the timestamp of the most recent successful data fetch, or null if never fetched. */
  getLastUpdate(): Date | null
  /** Returns true when this source is configured and reachable. */
  isAvailable(): boolean
}

// ---------------------------------------------------------------------------
// CollectorOptions — options for SessionDataCollector
// ---------------------------------------------------------------------------

/**
 * Configuration options for `SessionDataCollector`.
 *
 * `sources` is an injection point for testing — when provided, the collector
 * uses these instead of constructing the default InMemorySource / FileSource /
 * NetworkSource instances.
 */
export interface CollectorOptions {
  /** Absolute path to the repository root (used to locate .axiom/sessions/). */
  repoRoot: string
  /** When true, include team member sessions in the output (default: false). */
  includeTeam?: boolean
  /** Injected sources for testing; overrides default source construction when provided. */
  sources?: SessionDataSource[]
  /**
   * TTL in seconds for stopped sessions. Stopped sessions older than this value
   * are removed from the dashboard output. Default: 300 (5 minutes).
   *
   * REQ-TUI-015: stopped sessions MUST be removed after TTL expires.
   * axiom:trace work_item=tui-dashboard-01 spec=specs/89-TUI-Dashboard-Plugin.md#REQ-TUI-015 plan=step-verify-H001
   */
  stoppedTtlSeconds?: number
}
