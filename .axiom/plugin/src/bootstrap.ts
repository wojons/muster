/** Information about the repo detected during bootstrap */
export interface RepoInfo {
	/** Directory/project name */
	name: string;
	/** Detected languages */
	languages: string[];
	/** Detected frameworks */
	frameworks: string[];
	/** Whether CI config was found */
	hasCI: boolean;
}

/** Options for the bootstrap command */
export interface BootstrapOptions {
	/** REQ-PLG-017: --minimal flag — scaffold only .opencode/ and opencode.jsonc */
	minimal?: boolean;
}

/** Result of running /axiom-setup */
export interface BootstrapResult {
	/** Ordered list of steps that were completed (human-readable descriptions) */
	stepsCompleted: string[];
	/** 1-3 suggested next steps per REQ-PLG-011 step 7 */
	nextSteps: string[];
	/** Detected repo information per REQ-PLG-014 */
	repoInfo: RepoInfo;
}

