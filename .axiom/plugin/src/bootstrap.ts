/**
 * Write a file only if it does not already exist (REQ-PLG-012: idempotent).
 * Returns true if the file was created, false if it already existed.
 */
function writeIfMissing(filePath: string, content: string): boolean {
	if (existsSync(filePath)) return false;
	const dir = join(filePath, "..");
	mkdirSync(dir, { recursive: true });
	writeFileSync(filePath, content);
	return true;
}

/**
 * Ensure a directory exists. Returns true if it was created, false if it already existed.
 */
function ensureDir(dirPath: string): boolean {
	if (existsSync(dirPath)) return false;
	mkdirSync(dirPath, { recursive: true });
	return true;
}

/**
 * REQ-PLG-011 step 1: Detect repo type (language, framework, monorepo vs single).
 * REQ-PLG-014: Show the user what Axiom detected about their repo.
 */
function detectRepoType(repoRoot: string): RepoInfo {
	const name = tryReadPackageName(repoRoot) || basename(repoRoot);
	const languages: string[] = [];
	const frameworks: string[] = [];
	let hasCI = false;

	// Detect languages by file presence
	if (fileExists(repoRoot, "package.json")) languages.push("javascript");
	if (fileExists(repoRoot, "tsconfig.json")) languages.push("typescript");
	if (
		fileExists(repoRoot, "pyproject.toml") ||
		fileExists(repoRoot, "setup.py") ||
		fileExists(repoRoot, "requirements.txt")
	)
		languages.push("python");
	if (fileExists(repoRoot, "go.mod")) languages.push("go");
	if (fileExists(repoRoot, "Cargo.toml")) languages.push("rust");
	if (fileExists(repoRoot, "Gemfile")) languages.push("ruby");

	// Detect frameworks
	if (
		fileExists(repoRoot, "next.config.js") ||
		fileExists(repoRoot, "next.config.mjs") ||
		fileExists(repoRoot, "next.config.ts")
	)
		frameworks.push("nextjs");
	if (
		fileExists(repoRoot, "vite.config.ts") ||
		fileExists(repoRoot, "vite.config.js")
	)
		frameworks.push("vite");

	// Detect CI
	if (
		existsSync(join(repoRoot, ".github", "workflows")) ||
		fileExists(repoRoot, ".gitlab-ci.yml") ||
		fileExists(repoRoot, "Jenkinsfile")
	) {
		hasCI = true;
	}

	return { name, languages, frameworks, hasCI };
}

function fileExists(root: string, name: string): boolean {
	return existsSync(join(root, name));
}

function tryReadPackageName(repoRoot: string): string | null {
	try {
		const pkgPath = join(repoRoot, "package.json");
		if (!existsSync(pkgPath)) return null;
		const pkg = JSON.parse(readFileSync(pkgPath, "utf-8"));
		return typeof pkg.name === "string" && pkg.name.length > 0
			? pkg.name
			: null;
	} catch {
		return null;
	}
}

function tryReadPackageDescription(repoRoot: string): string | null {
	try {
		const pkgPath = join(repoRoot, "package.json");
		if (!existsSync(pkgPath)) return null;
		const pkg = JSON.parse(readFileSync(pkgPath, "utf-8"));
		return typeof pkg.description === "string" && pkg.description.length > 0
			? pkg.description
			: null;
	} catch {
		return null;
	}
}

function tryReadReadme(repoRoot: string): string | null {
	try {
		const readmePath = join(repoRoot, "README.md");
		if (!existsSync(readmePath)) return null;
		const content = readFileSync(readmePath, "utf-8");
		return content.length > 0 ? content : null;
	} catch {
		return null;
	}
}

/**
 * REQ-PLG-014: Generate a draft 00-PRD.md from repo context.
 */
function generateDraftPRD(repoRoot: string, repoInfo: RepoInfo): string {
	const description = tryReadPackageDescription(repoRoot) || "";
	const readme = tryReadReadme(repoRoot);

	let prd = `# ${repoInfo.name} — Product Requirements Document\n\n`;
	prd += `> **Status**: Draft (auto-generated by /axiom-setup)\n\n`;

	if (description) {
		prd += `## Overview\n\n${description}\n\n`;
	}

	if (repoInfo.languages.length > 0) {
		prd += `## Detected Stack\n\n`;
		prd += `- **Languages**: ${repoInfo.languages.join(", ")}\n`;
		if (repoInfo.frameworks.length > 0) {
			prd += `- **Frameworks**: ${repoInfo.frameworks.join(", ")}\n`;
		}
		prd += `\n`;
	}

	if (readme) {
		// Include a snippet of the README for context
		const snippet = readme.slice(0, 500);
		prd += `## From README\n\n${snippet}\n`;
		if (readme.length > 500)
			prd += `\n*(truncated — see README.md for full content)*\n`;
		prd += `\n`;
	}

	prd += `## Next Steps\n\n`;
	prd += `1. Edit this PRD to describe your product's purpose and goals\n`;
	prd += `2. Add requirements with IDs (e.g., REQ-001)\n`;
	prd += `3. Run \`/axiom-plan\` to create an implementation plan\n`;

	return prd;
}

/**
 * Run the /axiom-setup bootstrap flow.
 *
 * REQ-PLG-011: Performs steps in order:
 *   1. Detect repo type (language, framework, monorepo vs single)
 *   2. Scaffold .opencode/ directory with agents, commands, skills
 *   3. Scaffold specs/ with README.md, _prompt.md, _index.md, 00-PRD.md
 *   4. Scaffold .memory-bank/ with _prompt.md, _index.md
 *   5. Create or update opencode.jsonc with Axiom defaults
 *   6. Run health check on available backends
 *   7. Report what was created and suggest 1-3 next steps
 *
 * REQ-PLG-012: Idempotent — does not overwrite user-authored files.
 * REQ-PLG-014: Produces immediate visible value.
 * REQ-PLG-017: Supports --minimal flag.
 *
 * @param repoRoot - Absolute path to the repository root directory
 * @param options - Bootstrap options (e.g., minimal mode)
 * @returns BootstrapResult with steps completed, next steps, and repo info
 */
export async function bootstrap(
	repoRoot: string,
	options?: BootstrapOptions,
): Promise<BootstrapResult> {
	const minimal = options?.minimal ?? false;
	const stepsCompleted: string[] = [];

	// ── Step 1: Detect repo type ──────────────────────────────────────────
	const repoInfo = detectRepoType(repoRoot);

	// ── Step 2: Scaffold .opencode/ ───────────────────────────────────────
	const opencodeCreated = ensureDir(join(repoRoot, ".opencode"));
	const agentsCreated = ensureDir(join(repoRoot, ".opencode", "agents"));
	const commandsCreated = ensureDir(join(repoRoot, ".opencode", "commands"));
	const skillsCreated = ensureDir(join(repoRoot, ".opencode", "skills"));

	// REQ-PLG-017: --minimal includes copilot skill
	const copilotDir = join(repoRoot, ".opencode", "skills", "axiom-copilot");
	const copilotCreated = ensureDir(copilotDir);
	const copilotFileCreated = writeIfMissing(
		join(copilotDir, "SKILL.md"),
		COPILOT_SKILL,
	);

	if (
		opencodeCreated ||
		agentsCreated ||
		commandsCreated ||
		skillsCreated ||
		copilotCreated ||
		copilotFileCreated
	) {
		stepsCompleted.push(
			"Scaffolded .opencode/ directory with agents, commands, skills",
		);
	}

	if (!minimal) {
		// ── Step 3: Scaffold specs/ ───────────────────────────────────────────
		const specsCreated = ensureDir(join(repoRoot, "specs"));
		const readmeCreated = writeIfMissing(
			join(repoRoot, "specs", "README.md"),
			SPECS_README,
		);
		const promptCreated = writeIfMissing(
			join(repoRoot, "specs", "_prompt.md"),
			SPECS_PROMPT,
		);
		const indexCreated = writeIfMissing(
			join(repoRoot, "specs", "_index.md"),
			SPECS_INDEX,
		);
		const prdCreated = writeIfMissing(
			join(repoRoot, "specs", "00-PRD.md"),
			generateDraftPRD(repoRoot, repoInfo),
		);

		if (
			specsCreated ||
			readmeCreated ||
			promptCreated ||
			indexCreated ||
			prdCreated
		) {
			stepsCompleted.push(
				"Scaffolded specs/ with README.md, _prompt.md, _index.md, 00-PRD.md",
			);
		}

		// ── Step 4: Scaffold .memory-bank/ ────────────────────────────────────
		const mbCreated = ensureDir(join(repoRoot, ".memory-bank"));
		const mbPromptCreated = writeIfMissing(
			join(repoRoot, ".memory-bank", "_prompt.md"),
			MEMORY_BANK_PROMPT,
		);
		const mbIndexCreated = writeIfMissing(
			join(repoRoot, ".memory-bank", "_index.md"),
			MEMORY_BANK_INDEX,
		);

		if (mbCreated || mbPromptCreated || mbIndexCreated) {
			stepsCompleted.push(
				"Scaffolded .memory-bank/ with _prompt.md, _index.md",
			);
		}
	}

	// ── Step 5: Create or update opencode.jsonc ─────────────────────────
	const configCreated = writeIfMissing(
		join(repoRoot, "opencode.jsonc"),
		OPENCODE_JSONC_TEMPLATE,
	);
	if (configCreated) {
		stepsCompleted.push("Created opencode.jsonc with Axiom defaults");
	}

	// ── Step 6: Health check on available backends ────────────────────────
	// REQ-PLG-011 step 6: Run health check on available backends
	// Uses detectBackends() from detect.ts for a real backend probe.
	const backends: BackendInfo = detectBackends(repoRoot);
	const backendParts: string[] = [];
	if (backends.python) backendParts.push("python");
	if (backends.go) backendParts.push("go");
	const backendSummary =
		backendParts.length > 0 ? backendParts.join(" + ") : "no backends detected";
	stepsCompleted.push(
		`Checked backend health (${backends.mode} mode — ${backendSummary})`,
	);

	// ── Step 7: Report + suggest next steps ───────────────────────────────
	const nextSteps: string[] = [];
	if (minimal) {
		nextSteps.push(
			"Run /axiom-setup again without --minimal to scaffold specs and memory bank",
		);
		nextSteps.push(
			"Edit opencode.jsonc to customize your Axiom configuration",
		);
	} else {
		if (existsSync(join(repoRoot, "specs", "00-PRD.md"))) {
			nextSteps.push(
				"Edit specs/00-PRD.md to describe your product's purpose and goals",
			);
		}
		nextSteps.push(
			"Run /axiom-plan to create your first implementation plan",
		);
		if (!repoInfo.hasCI) {
			nextSteps.push("Set up CI/CD to unlock Level 4 (Mature) features");
		}
	}

	// Ensure 1-3 next steps
	if (nextSteps.length === 0) {
		nextSteps.push("Explore your new Axiom setup with /axiom-help");
	}
	while (nextSteps.length > 3) {
		nextSteps.pop();
	}

	return {
		stepsCompleted,
		nextSteps,
		repoInfo,
	};
}
