// ── REQ-PLG-041: Template rendering ─────────────────────────────────────

/**
 * Render a template string by replacing {{key}} placeholders with values
 * from the provided params. Unknown placeholders are left untouched.
 * Null values are rendered as the string "null".
 */
export function renderTemplate(
	template: string,
	params: TemplateParams,
): string {
	return template.replace(/\{\{(\w+)\}\}/g, (match, key: string) => {
		if (key in params) {
			const value = (params as Record<string, unknown>)[key];
			return value === null ? "null" : String(value ?? match);
		}
		return match; // leave unknown placeholders untouched
	});
}

// ── REQ-PLG-044 + REQ-PLG-045: Manifest computation ────────────────────

/**
 * Compute the scaffold manifest for a repo directory.
 *
 * REQ-PLG-044: Detects existing files and skips them.
 * REQ-PLG-045: Records template version for each created file.
 *
 * @param repoRoot - Absolute path to the repository root
 * @param params - Template parameters for rendering
 * @returns TemplateManifest with toCreate, toSkip, and templateVersion
 */
export function getTemplateManifest(
	repoRoot: string,
	params: TemplateParams,
): TemplateManifest {
	const toCreate: ManifestCreateEntry[] = [];
	const toSkip: ManifestSkipEntry[] = [];

	for (const entry of TEMPLATE_INVENTORY) {
		const fullPath = join(repoRoot, entry.path);

		if (existsSync(fullPath)) {
			// REQ-PLG-044: skip existing files
			toSkip.push({
				path: entry.path,
				reason: `${entry.path} already exists — skipping to preserve user content`,
			});
		} else {
			// Render template with params and record version
			const rendered = renderTemplate(entry.content, params);
			toCreate.push({
				path: entry.path,
				content: rendered,
				version: entry.version,
			});
		}
	}

	return {
		toCreate,
		toSkip,
		templateVersion: TEMPLATE_VERSION,
	};
}
