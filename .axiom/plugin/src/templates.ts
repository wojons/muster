// ── Types ───────────────────────────────────────────────────────────────

/** A single scaffold template entry. */
export interface TemplateEntry {
	/** Relative path from repo root (e.g., "opencode.jsonc") */
	path: string;
	/** Raw template content (may contain {{placeholder}} tokens) */
	content: string;
	/** Template version per REQ-PLG-045 */
	version: string;
}

/** Parameters for template rendering per REQ-PLG-041. */
export interface TemplateParams {
	/** From git remote or directory name */
	repo_name?: string;
	/** org/repo format, auto-derived from git remote */
	repo_id?: string;
	/** Jira project key; null if not provided */
	jira_project_key?: string | null;
	/** Auto-detected primary language */
	primary_language?: string;
	/** Auto-detected framework */
	framework?: string;
	/** Current date (YYYY-MM-DD) */
	date?: string;
}

/** A file that should be created during scaffolding. */
export interface ManifestCreateEntry {
	path: string;
	content: string;
	version: string;
}

/** A file that was skipped during scaffolding. */
export interface ManifestSkipEntry {
	path: string;
	reason: string;
}

/** Result of computing the scaffold manifest for a repo. */
export interface TemplateManifest {
	/** Files to create (do not exist yet) */
	toCreate: ManifestCreateEntry[];
	/** Files to skip (already exist) */
	toSkip: ManifestSkipEntry[];
	/** Template version used for this manifest */
	templateVersion: string;
}

